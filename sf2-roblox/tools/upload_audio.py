"""Upload the audio packs (tools/build_audio.py) to the user's Roblox account with the Open Cloud Assets API,
then write out/AudioMap.lua: clip -> {assetId, start, length} for SF2.Sound.
Resumable: finished uploads are kept in sf2-assets/audio_uploads.json and skipped next time.
The API key is read from sf2-data/keys/roblox_api_key.txt (never printed).
Run: python -I tools/upload_audio.py
"""
import json, os, sys, time, uuid, urllib.request, urllib.error

ASSETS = 'D:/SF2-Port/sf2-assets'
KEY = open('D:/SF2-Port/sf2-data/keys/roblox_api_key.txt', encoding='utf-8-sig').read().strip()
USER_ID = 968421912
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'out')
DONE = os.path.join(ASSETS, 'audio_uploads.json')
API = 'https://apis.roblox.com/assets/v1/'

def call(method, url, body=None, headers=None):
    req = urllib.request.Request(url, data=body, method=method, headers={'x-api-key': KEY, **(headers or {})})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.load(r)

def upload(path, name):
    boundary = uuid.uuid4().hex
    request = json.dumps({
        'assetType': 'Audio', 'displayName': name, 'description': 'SF2 port audio pack (private)',
        'creationContext': {'creator': {'userId': str(USER_ID)}},
    })
    data = open(path, 'rb').read()
    body = (f'--{boundary}\r\nContent-Disposition: form-data; name="request"\r\n\r\n{request}\r\n'
            f'--{boundary}\r\nContent-Disposition: form-data; name="fileContent"; filename="{os.path.basename(path)}"\r\n'
            f'Content-Type: audio/ogg\r\n\r\n').encode() + data + f'\r\n--{boundary}--\r\n'.encode()
    op = call('POST', API + 'assets', body, {'Content-Type': f'multipart/form-data; boundary={boundary}'})
    path_ = op.get('path') or ('operations/' + op['operationId'])
    for _ in range(120):
        if op.get('done'):
            break
        time.sleep(3)
        op = call('GET', API + path_)
    if not op.get('done'):
        raise RuntimeError('operation not done: ' + json.dumps(op)[:300])
    if 'error' in op:
        raise RuntimeError(json.dumps(op['error'])[:500])
    return op['response']['assetId']

def write_map(done):
    index = json.load(open(os.path.join(ASSETS, 'audio_index.json')))
    lines = ['-- Generated by tools/upload_audio.py: clip -> {assetId, start, length} (seconds in the pack)', 'return {']
    missing = 0
    for clip, (pack, start, length) in sorted(index.items()):
        aid = done.get(pack)
        if aid:
            lines.append(f'\t["{clip}"] = {{{aid},{start},{length}}},')
        else:
            missing += 1
    lines.append('}\n')
    open(os.path.join(OUT, 'AudioMap.lua'), 'w', encoding='utf8', newline='\n').write('\n'.join(lines))
    print('AudioMap:', len(index) - missing, 'clips mapped,', missing, 'still without an upload')

def main():
    done = json.load(open(DONE)) if os.path.exists(DONE) else {}
    packs = sorted((f[:-4] for f in os.listdir(os.path.join(ASSETS, 'audio_packs')) if f.endswith('.ogg')),
                   key=lambda n: (not n.startswith('sfx'), int(n.split('_')[1])))
    for name in packs:
        if name in done:
            continue
        try:
            aid = upload(os.path.join(ASSETS, 'audio_packs', name + '.ogg'), 'SF2 ' + name)
        except urllib.error.HTTPError as e:
            print(name, 'HTTP', e.code, e.read()[:400].decode(errors='replace'))
            break
        except Exception as e:
            print(name, 'failed:', str(e)[:400])
            break
        done[name] = aid
        json.dump(done, open(DONE, 'w'), indent=1)
        print(name, '->', aid, flush=True)
    write_map(done)

if __name__ == '__main__':
    main()
