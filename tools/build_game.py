LANGS = ['eng', 'rus', 'ger', 'fra', 'ita', 'spa', 'por', 'tur', 'chn', 'chn_tr', 'jpn', 'kor']

def lstr(v):
    v = v.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '')
    return '"' + v + '"'

KEY = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')

def attrs(el):
    items = []
    for k, v in el.attrib.items():
        items.append((k if KEY.match(k) else f'[{lstr(k)}]') + '=' + lstr(v))
    return '{' + ','.join(items) + '}'

def ser(el):
    parts = [f't={lstr(el.tag)}']
    if el.attrib:
        parts.append('a=' + attrs(el))
    kids = list(el)
    if kids:
        parts.append('c={' + ','.join(ser(c) for c in kids) + '}')
    text = (el.text or '').strip()
    if text:
        parts.append('x=' + lstr(text))
    return '{' + ','.join(parts) + '}'

class Writer:
    def __init__(self, folder, name):
        self.folder, self.name, self.n = folder, name, 0
        os.makedirs(folder, exist_ok=True)

    def module(self, body):
        """Write one part module, return its name."""
        self.n += 1
        mod = f'{self.name}.{self.n}'
        open(os.path.join(self.folder, mod + '.lua'), 'w', encoding='utf8', newline='\n').write(
            f'-- Generated by tools/build_game.py\nreturn {body}\n')
        return mod

    def element(self, el):
        """Serialized element, splitting children into part modules when too big."""
        s = ser(el)
        if len(s.encode('utf8')) < MAX_SOURCE:
            return s
        parts = [f't={lstr(el.tag)}']
        if el.attrib:
            parts.append('a=' + attrs(el))
        mods, chunk, size = [], [], 0
        for c in el:
            cs = self.element(c)
            if size + len(cs.encode('utf8')) > MAX_SOURCE and chunk:
                mods.append(self.module('{' + ','.join(chunk) + '}'))
                chunk, size = [], 0
            chunk.append(cs); size += len(cs.encode('utf8')) + 1
        if chunk:
            mods.append(self.module('{' + ','.join(chunk) + '}'))
        parts.append('p={' + ','.join(lstr(m) for m in mods) + '}')
        return '{' + ','.join(parts) + '}'

def clear(folder, name):
    if not os.path.isdir(folder):
        return
    for f in os.listdir(folder):
        if f == name + '.lua' or (f.startswith(name + '.') and f[len(name) + 1:-4].isdigit()):
            os.remove(os.path.join(folder, f))

def write_doc(folder, name, root):
    clear(folder, name)
    w = Writer(folder, name)
    body = w.element(root)
    open(os.path.join(folder, name + '.lua'), 'w', encoding='utf8', newline='\n').write(
        f'-- Generated by tools/build_game.py\nreturn {body}\n')
    return w.n

def parse(path):
    data = open(path, 'rb').read()
    if data.startswith(b'\xef\xbb\xbf'):
        data = data[3:]
    return ET.fromstring(data)

def locations():
    """Every *_params location layout (APK + event packs)."""
    found = {}
    for f in os.listdir(f'{DEC}/apk'):
        if f.endswith('_params'):
            found[f[:-7]] = f'{DEC}/apk/{f}'
    for d, _, files in os.walk(MORE):
        for f in files:
            if f.endswith('_params') and f[:-7] not in found:
                p = os.path.join(d, f)
                head = open(p, 'rb').read(64)
                if b'<' in head[:8] or head.startswith(b'\xef\xbb\xbf<'):
                    found[f[:-7]] = p
    return found

def write_lang(folder, lang, path):
    os.makedirs(folder, exist_ok=True)
    root = parse(path)
    words = root.find('Words')
    entries = []
    for w in (words if words is not None else []):
        title = w.get('Title')
        if title is None:
            continue
        text = ''.join(w.itertext())
        entries.append(f'[{lstr(title)}]={lstr(text)}')
    clear(folder, lang)
    mods, chunk, size, n = [], [], 0, 0
    for e in entries:
        if size + len(e.encode('utf8')) > MAX_SOURCE and chunk:
            n += 1
            mods.append(f'{lang}.{n}')
            open(os.path.join(folder, f'{lang}.{n}.lua'), 'w', encoding='utf8', newline='\n').write(
                '-- Generated by tools/build_game.py\nreturn {' + ',\n'.join(chunk) + '}\n')
            chunk, size = [], 0
        chunk.append(e); size += len(e.encode('utf8')) + 2
    n += 1
    mods.append(f'{lang}.{n}')
    open(os.path.join(folder, f'{lang}.{n}.lua'), 'w', encoding='utf8', newline='\n').write(
        '-- Generated by tools/build_game.py\nreturn {' + ',\n'.join(chunk) + '}\n')
    open(os.path.join(folder, lang + '.lua'), 'w', encoding='utf8', newline='\n').write(
        '-- Generated by tools/build_game.py: the string table is joined from its parts\n'
        'local t = {}\nfor _, n in {' + ','.join(lstr(m) for m in mods) + '} do\n'
        '\tfor k, v in require(script.Parent:FindFirstChild(n)) do t[k] = v end\nend\nreturn t\n')
    return len(entries)

def main():
    xml_dir = os.path.join(OUT, 'Xml')
    for name, path in DOCS.items():
        if not os.path.exists(path):
            print('missing', name, path); continue
        try:
            n = write_doc(xml_dir, name, parse(path))
        except ET.ParseError as e:
            print('unparsed', name, e); continue
        print('doc', name, 'parts', n)
    loc_dir = os.path.join(OUT, 'Locations')
    locs = locations()
    bad = []
    for name, path in sorted(locs.items()):
        try:
            write_doc(loc_dir, name, parse(path))
        except ET.ParseError:
            bad.append(name)
    print('locations', len(locs) - len(bad), 'unparsed', bad)
    lang_dir = os.path.join(OUT, 'Lang')
    for lang in LANGS:
        p = f'{DEC}/bundles/localizations/{lang}'
        if os.path.exists(p):
            print('lang', lang, write_lang(lang_dir, lang, p))

if __name__ == '__main__':
    main()
