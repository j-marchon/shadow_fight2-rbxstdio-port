"""Convert the game's XML configs, location layouts and localizations into Luau modules, unchanged.
Every element becomes {t="Tag", a={attr=value,...}, c={children...}, x="text"} (a/c/x omitted when empty);
all attribute values stay strings, exactly as in the XML, and SF2.Xml reads them at runtime.
A document whose source would pass MAX_SOURCE is split: an element too big for one module keeps its
children in sibling modules <name>.<n> and lists them in p={...} (SF2.Xml joins them on load).
Output: out/Xml/<doc>.lua (+ parts), out/Lang/<lang>.lua (Title -> text maps, split the same way).
Run: python -I tools/build_game.py
"""
import os, re, sys
import xml.etree.ElementTree as ET

DEC = 'D:/Tools/work/sf2-data/decrypted'
